function includesAny(text: string, keywords: string[]): boolean {
  return keywords.some((k) => text.includes(k));
}

export function answerTopicQuestion(category: ActionCategory, question: string): string {
  const text = question.trim();

  if (includesAny(text, ["چرا", "دلیل"])) {
    return RATIONALE[category];
  }
  if (includesAny(text, ["سخت", "نمی‌تونم", "نمیتونم", "نمی تونم", "محدودیت"])) {
    return ALTERNATIVE[category];
  }
  if (includesAny(text, ["چقدر", "چند بار", "چند روز", "چند وقت"])) {
    return "بهتره این رو به‌صورت پایدار و کم‌کم انجام بدی، نه یکباره و پرفشار. جزئیات دقیق‌تر توی همون صفحه‌ی اقدام نوشته شده.";
  }

  return "این سوالت رو یادداشت کردم. اگه می‌خوای رسمی‌تر گزارشش کنی، از همون صفحه‌ی اقدام روی دکمه‌های «مشکل دارم» یا «محدودیتی دارم» بزن تا بررسی بشه.";
}
